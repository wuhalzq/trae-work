def generate_image(title, candidates, filename, columns, col_labels, col_widths):
    n = len(candidates)
    fig_height = max(3.5, 1.2 + n * 0.48)
    fig, ax = plt.subplots(figsize=(14, fig_height))
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis('off')

    ax.text(0.5, 0.97, title, transform=ax.transAxes,
            fontsize=18, fontweight='bold', ha='center', va='top',
            color='#1a1a2e',
            bbox=dict(boxstyle='round,pad=0.4', facecolor='#e8f4f8', edgecolor='#2196F3', linewidth=2))

    ax.text(0.5, 0.92, f"数据日期: {DATE_DISPLAY}  |  数据来源: 同花顺人气榜 + 东方财富涨停数据",
            transform=ax.transAxes, fontsize=9, ha='center', va='top', color='#666666')

    table_data = [col_labels]
    for c in candidates:
        row = []
        for i, col_fn in enumerate(columns):
            val = col_fn(c)
            row.append(str(val))
        table_data.append(row)

    table = ax.table(cellText=table_data[1:],
                     colLabels=table_data[0],
                     cellLoc='center',
                     loc='center',
                     bbox=[0.02, 0.02, 0.96, 0.87])

    table.auto_set_font_size(False)
    table.set_fontsize(9)

    for i, w in enumerate(col_widths):
        for j in range(len(table_data)):
            table[(j, i)].set_width(w)

    for i in range(len(col_labels)):
        cell = table[(0, i)]
        cell.set_facecolor('#2196F3')
        cell.set_text_props(color='white', fontweight='bold', fontsize=10)
        cell.set_edgecolor('#1565C0')

    for i in range(1, len(table_data)):
        for j in range(len(col_labels)):
            cell = table[(i, j)]
            if i % 2 == 0:
                cell.set_facecolor('#f5f5f5')
            else:
                cell.set_facecolor('#ffffff')
            cell.set_edgecolor('#e0e0e0')
            cell.set_height(0.065)

            if j == 3:
                try:
                    val = float(table_data[i][j].replace('%', ''))
                    if val > 0:
                        cell.set_text_props(color='#e53935', fontweight='bold')
                    elif val < 0:
                        cell.set_text_props(color='#43a047', fontweight='bold')
                except:
                    pass

    plt.tight_layout()
    filepath = os.path.join(SAVE_DIR, filename)
    plt.savefig(filepath, dpi=150, bbox_inches='tight', facecolor='white')
    plt.close()
    print(f"\n图片已保存: {filepath}")
    return filepath

