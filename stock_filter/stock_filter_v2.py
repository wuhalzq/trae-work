def is_main_board(code):
    return code.startswith('60') or code.startswith('00')

def is_st(name):
    return 'ST' in name.upper()

def get_popularity_rank(code):
    for item in popularity_top150:
        if item[1] == code:
            return item[0]
    return 999

def get_popularity_info(code):
    for item in popularity_top150:
        if item[1] == code:
            return item
    return None

