def send_text(content):
    data = {"msgtype": "text", "text": {"content": content}}
    resp = requests.post(WEBHOOK_URL, json=data, timeout=30)
    return resp.json()

def send_image(base64_data, md5):
    data = {"msgtype": "image", "image": {"base64": base64_data, "md5": md5}}
    resp = requests.post(WEBHOOK_URL, json=data, timeout=30)
    return resp.json()

def file_to_base64(filepath):
    with open(filepath, 'rb') as f:
        data = f.read()
    return base64.b64encode(data).decode('utf-8'), hashlib.md5(data).hexdigest()

